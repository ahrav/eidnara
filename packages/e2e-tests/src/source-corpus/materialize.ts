import { spawnSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";

import { SOURCE_CORPUS_DIR } from "./corpus.ts";

const { mkdirSync, readFileSync, symlinkSync, writeFileSync } = process.getBuiltinModule("node:fs");

export interface RepositoryManifest {
    readonly schema: string;
    readonly name: string;
    readonly layout: string;
    readonly instructions: string;
    readonly upstream: {
        readonly repository: string;
        readonly commit: string;
        readonly license: string;
    };
    readonly documents: readonly { readonly path: string; readonly text: string }[];
    readonly files: readonly (
        | { readonly path: string; readonly size: number; readonly utf8: boolean }
        | { readonly path: string; readonly symlink: string }
    )[];
}

export function readManifest(name: string, dir: string = SOURCE_CORPUS_DIR): RepositoryManifest {
    const text = readFileSync(join(dir, "repos", `${name}.json`), "utf8");
    let manifest: RepositoryManifest;
    try {
        manifest = JSON.parse(text) as RepositoryManifest;
    } catch (error) {
        throw new Error(`repos/${name}.json is not JSON: ${String(error)}`);
    }
    return manifest;
}

const FILLER = Buffer.from("source corpus filler\n");

/** The Rust materializer's regenerated bytes: the filler cycled to `size`, led by 0xFF when not UTF-8. */
export function generatedBytes(size: number, utf8: boolean): Buffer {
    const bytes = Buffer.alloc(size);
    for (let at = 0; at < size; at += FILLER.length) FILLER.copy(bytes, at, 0, size - at);
    if (!utf8 && size > 0) bytes[0] = 0xff;
    return bytes;
}

/** Git with a cleared environment, absolute `PATH` entries only, and the Rust peer's fixed identity and dates. */
export function git(dir: string, args: readonly string[]): string {
    const path = (process.env.PATH ?? "")
        .split(":")
        .filter((entry) => entry.startsWith("/"))
        .join(":");
    const result = spawnSync("git", args, {
        cwd: dir,
        encoding: "utf8",
        env: {
            PATH: path,
            GIT_CONFIG_NOSYSTEM: "1",
            GIT_CONFIG_GLOBAL: "/dev/null",
            GIT_ATTR_NOSYSTEM: "1",
            GIT_AUTHOR_NAME: "corpus",
            GIT_AUTHOR_EMAIL: "corpus@example.invalid",
            GIT_AUTHOR_DATE: "@1700000000 +0000",
            GIT_COMMITTER_NAME: "corpus",
            GIT_COMMITTER_EMAIL: "corpus@example.invalid",
            GIT_COMMITTER_DATE: "@1700000000 +0000",
        },
    });
    if (result.status !== 0) throw new Error(`git ${args.join(" ")} failed: ${result.stderr}`);
    return result.stdout;
}

/**
 * Writes `manifest` under `parent` as `checkout/`, a one-commit git repository, the same commit the
 * Rust materializer produces for the same manifest.
 */
export function materialize(manifest: RepositoryManifest, parent: string): string {
    const root = resolve(parent, "checkout");
    const target = (path: string) => {
        const full = join(root, path);
        mkdirSync(dirname(full), { recursive: true });
        return full;
    };
    mkdirSync(root, { recursive: true });
    for (const document of manifest.documents) writeFileSync(target(document.path), document.text);
    for (const file of manifest.files) {
        if ("symlink" in file) symlinkSync(file.symlink, target(file.path));
        else writeFileSync(target(file.path), generatedBytes(file.size, file.utf8));
    }
    if (manifest.layout === "non_git") return root;
    git(root, ["init", "-q", "-b", "main", "--object-format=sha1"]);
    git(root, ["add", "-A", "-f"]);
    git(root, ["commit", "-q", "--no-verify", "-m", manifest.name]);
    return root;
}
