/** Generated by `build:tui` from `src/tui`; its modules are that tree's, not new source. */
const GENERATED = new Set([join(SRC, "tui-compiled")]);

function sourceFiles(dir: string, acc: string[] = [], skipGenerated = true): string[] {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name);
        if (skipGenerated && GENERATED.has(full)) continue;
        if (entry.isDirectory()) sourceFiles(full, acc, skipGenerated);
        else if (CODE_FILE.test(entry.name)) acc.push(full);
    }
    return acc;
}

