type ReportedGraph = Omit<ModuleGraph, "text">;

let cachedReport: Record<string, ReportedGraph> | undefined;

/** Two tests read the report; each root is bundled once per test file run. */
function moduleGraphReport(): Record<string, ReportedGraph> {
    if (cachedReport) return cachedReport;
    const report = Bun.spawnSync({
        cmd: ["bun", join(import.meta.dir, "module-graph-report.ts"), ...ROOTS],
        cwd: SRC,
        stdout: "pipe",
        stderr: "pipe",
    });
    if (report.exitCode !== 0) {
        throw new Error(`module graph report failed: ${report.stderr.toString()}`);
    }
    cachedReport = JSON.parse(report.stdout.toString());
    return cachedReport as Record<string, ReportedGraph>;
}

const PRODUCTION_ROOTS = [ENTRY, TUI_ENTRY];

/**
 * Every first-party file a production root bundles, wherever it lives: the retained tree, a
 * sibling workspace package, a JSON data file, but not a third-party dependency. A production
 * root must never reach a test-named file, since the state-ownership scans select by file name.
 */
function productionReached(): string[] {
    const graphs = moduleGraphReport();
    const reached = new Set<string>();
    for (const root of PRODUCTION_ROOTS) {
        const graph = graphs[root];
        if (!graph) throw new Error(`no graph for production root ${root}`);
        const inputs = firstPartyInputs(graph);
        for (const input of [...inputs.code, ...inputs.data]) reached.add(resolve(SRC, input));
    }
    const testNamed = [...reached].filter((file) => TEST_FILE.test(file));
    expect(testNamed).toEqual([]);
    return [...reached].sort();
}

/**
 * The retained tree, whatever production reaches outside it, and the generated compiled TUI
 * that the `./tui` export loads at runtime; the compiled tree is not a module source for the
 * orphan check, but its bytes ship, so the literal and database scans read them.
 */
function scannedSources(): string[] {
    const compiled = [...GENERATED].flatMap((dir) => sourceFiles(dir, [], false));
    return [...new Set([...MODULES, ...productionReached(), ...compiled])].sort();
}

/** `literalScanSources` excludes `SCAN_DEFINITIONS` because `OPERATION_LITERAL` expands to `"claim.` in that file; `productionReached` must never name it. */
const SCAN_DEFINITIONS = join(SRC, "testing/module-graph.ts");

function literalScanSources(): string[] {
    expect(productionReached()).not.toContain(SCAN_DEFINITIONS);
    return scannedSources().filter((file) => file !== SCAN_DEFINITIONS);
}

